#!/usr/bin/env python3
"""Validate ARTB task files and rebuild tasks/README.md.

Usage:
  python3 scripts/validate.py          # validate and rewrite the index
  python3 scripts/validate.py --check  # validate; fail if the index is stale
"""
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
TASKS = ROOT / "tasks"
INDEX = TASKS / "README.md"

DIMENSIONS = {
    "recommendation_quality", "online_task", "purchasing", "permissions_privacy",
    "email_replies", "third_party_integrations", "memory", "travel", "phone_calls",
    "proactive_behavior", "running_routine", "content_creation_games",
    "proactive_restraint", "chained_tasks", "multiplayer_groups", "personality",
    "data_access", "china_local",
}
BOARDS = {"core", "china_local", "global_local"}
CATEGORIES = {"comms", "travel", "shopping", "web", "schedule", "research", "files"}
REQUIRED = ["id", "slug", "task_version", "board", "category", "dimensions", "safety", "title",
            "scenario", "prompt", "params", "setup", "limits", "criteria", "evidence"]
BILINGUAL = ["title", "scenario", "prompt"]
OUTCOMES = ["pass", "partial", "fail"]


def bilingual(value, where, errors):
    if not isinstance(value, dict) or not value.get("en") or not value.get("zh"):
        errors.append(f"{where}: needs non-empty 'en' and 'zh'")


def validate(path, task, errors):
    where = path.relative_to(ROOT)
    missing = [key for key in REQUIRED if key not in task]
    if missing:
        errors.append(f"{where}: missing {', '.join(missing)}")
        return
    if task["board"] not in BOARDS:
        errors.append(f"{where}: unknown board '{task['board']}'")
    if task["category"] not in CATEGORIES:
        errors.append(f"{where}: unknown category '{task['category']}'")
    if path.parent.name != task["board"]:
        errors.append(f"{where}: file must live in tasks/{task['board']}/")
    if path.stem != f"{task['id']}-{task['slug']}":
        errors.append(f"{where}: filename must be '{task['id']}-{task['slug']}.yaml'")
    for dim in task["dimensions"]:
        if dim not in DIMENSIONS:
            errors.append(f"{where}: unknown dimension '{dim}'")
    for key in BILINGUAL:
        bilingual(task[key], f"{where}: {key}", errors)
    if "interruption" in task:
        bilingual(task["interruption"], f"{where}: interruption", errors)
    if "tester_reply" in task:
        bilingual(task["tester_reply"], f"{where}: tester_reply", errors)
    criteria = task["criteria"]
    for outcome in OUTCOMES:
        bilingual(criteria.get(outcome), f"{where}: criteria.{outcome}", errors)
    if task["safety"] and "violation" not in criteria:
        errors.append(f"{where}: safety task needs criteria.violation")
    if not task["safety"] and "violation" in criteria:
        errors.append(f"{where}: criteria.violation is only allowed on safety tasks")
    if "violation" in criteria:
        bilingual(criteria["violation"], f"{where}: criteria.violation", errors)
    for param in task["params"]:
        for lang in ("en", "zh"):
            if "{" + param["name"] + "}" not in task["prompt"][lang]:
                errors.append(f"{where}: param '{param['name']}' unused in prompt.{lang}")


def load():
    tasks, errors, seen = [], [], set()
    for path in sorted(TASKS.glob("*/*.yaml")):
        task = yaml.safe_load(path.read_text(encoding="utf-8"))
        validate(path, task, errors)
        if task.get("id") in seen:
            errors.append(f"{path}: duplicate id {task['id']}")
        seen.add(task.get("id"))
        tasks.append((path, task))
    return tasks, errors


def index(tasks):
    lines = [
        "# Task index · 任务索引",
        "",
        "Generated by `scripts/validate.py`. Do not edit by hand.",
        "由 `scripts/validate.py` 自动生成，请勿手动修改。",
        "",
    ]
    titles = {"core": "Core · 通用任务", "china_local": "China local · 中国本地",
              "global_local": "Global local · 海外本地"}
    for board in ("core", "china_local", "global_local"):
        rows = [(p, t) for p, t in tasks if t["board"] == board]
        lines += [f"## {titles[board]} ({len(rows)})", "",
                  "| ID | Task | 任务 | Dimensions | Safety |", "|---|---|---|---|---|"]
        for p, t in rows:
            link = p.relative_to(TASKS).as_posix()
            safety = "✓" if t["safety"] else ""
            lines.append(f"| [{t['id']}]({link}) | {t['title']['en']} | {t['title']['zh']} | "
                         f"{', '.join(t['dimensions'])} | {safety} |")
        lines.append("")
    return "\n".join(lines)


def main():
    tasks, errors = load()
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    text = index(tasks)
    if "--check" in sys.argv:
        if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != text:
            print("tasks/README.md is stale; run python3 scripts/validate.py")
            sys.exit(1)
    else:
        INDEX.write_text(text, encoding="utf-8")
    print(f"OK: {len(tasks)} tasks")


if __name__ == "__main__":
    main()
